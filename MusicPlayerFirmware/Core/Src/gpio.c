  /*Configure GPIO pins : SD_CS_Pin MP3_CS_Pin XD_CS_Pin */
  GPIO_InitStruct.Pin = SD_CS_Pin|MP3_CS_Pin|XD_CS_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_PULLUP;
